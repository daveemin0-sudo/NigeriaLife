// Draw calls on Broad Street, and the new places: the viewing centre, the terminal, a class, the estate (scratch capture)
import { launch, newPlayer, wait, advance, enterInterior, useStation } from './lib.mjs';
const out = process.argv[2];
const browser = await launch();
const ctx = await newPlayer(browser);
const page = await ctx.newPage();
await page.setViewport({ width: 420, height: 816, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
await page.goto(process.env.GAME_URL, { waitUntil: 'load', timeout: 120000 });
await page.waitForFunction('window.game', { timeout: 120000 });
await wait(8000);
await page.evaluate(() => { document.getElementById('dialogue-confirm-btn')?.click(); window.game.world.skyEnvironment.setHour(15); });
await advance(page, 1);
const calls = await page.evaluate(() => { const g = window.game; g.renderer.render(g.scene, g.cameraManager.camera); return { calls: g.renderer.info.render.calls, tris: g.renderer.info.render.triangles }; });
console.log('broad street', JSON.stringify(calls));
const shot = async (name) => { await wait(400); await page.screenshot({ path: `${out}/new-${name}.png` }); };
await enterInterior(page, 'interior_place_viewing-centre');
await advance(page, 8);
await shot('viewing');
await page.evaluate(() => { const g = window.game; return g.world.interiorManager.exitCurrentInterior(g.player, g.cameraManager, g.hud, g.world); });
await wait(1500);
await enterInterior(page, 'interior_place_mmia-terminal');
await advance(page, 6);
await shot('terminal');
await page.evaluate(() => { const g = window.game; return g.world.interiorManager.exitCurrentInterior(g.player, g.cameraManager, g.hud, g.world); });
await wait(1500);
await enterInterior(page, 'unilag');
await wait(800);
await page.evaluate(() => { const g = window.game; const o = g.world.interiorManager.getActiveInteractiveObjects().find((x) => x.id === 'unilag_lecture_podium'); g.player.mesh.position.copy(o.interactionPoint); g.hud.showInteractionCard(o); document.getElementById('card-action-btn')?.click(); });
await advance(page, 4);
await page.evaluate(() => [...document.querySelectorAll('#dialogue-choices-row .dialogue-choice-btn')].find((b) => /ECO 101/.test(b.innerText))?.click());
await advance(page, 7);
await shot('class');
await page.evaluate(() => { const g = window.game; return g.world.interiorManager.exitCurrentInterior(g.player, g.cameraManager, g.hud, g.world); });
await wait(1500);
await page.evaluate(() => { const g = window.game; g.player.stopMoving(); g.player.mesh.position.set(172, 0, 12); });
await advance(page, 2);
await shot('estate');
await browser.close();
