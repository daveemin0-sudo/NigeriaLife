// Pictures of a stay at the Eko Grand (scratch capture, not a suite)
import { launch, open, newPlayer, closeDialogs, wait, playUntil, advance } from './lib.mjs';
const out = process.argv[2];
const browser = await launch();
const ctx = await newPlayer(browser);
const { page } = await open(ctx, { w: 1366, h: 768 });
await closeDialogs(page);
const inRoom = (id) => playUntil(page, (want) => { const im = window.game.world.interiorManager; return im.currentInterior?.id === want && !im.busy ? true : null; }, 25, id);
const play = async (seconds) => { for (let t = 0; t < seconds; t += 0.5) { await advance(page, 0.5); await wait(15); } };
const use = async (id, choice) => {
  await page.evaluate((cid) => {
    const g = window.game;
    const o = g.world.interiorManager.getActiveInteractiveObjects().find((x) => x.id === cid);
    g.player.stopMoving();
    g.player.mesh.position.set(o.interactionPoint.x, 0, o.interactionPoint.z);
    g.hud.showInteractionCard(o);
    document.getElementById('card-action-btn')?.click();
  }, id);
  await wait(300);
  if (choice) await page.evaluate((t) => [...document.querySelectorAll('#game-dialogue-overlay button')].find((b) => b.textContent.includes(t))?.click(), choice);
};
const view = (yaw, pitch, distance) => page.evaluate(({ yaw, pitch, distance }) => { const c = window.game.cameraManager; c.interiorYaw = yaw; c.interiorPitch = pitch; c.interiorDistance = distance; }, { yaw, pitch, distance });

await page.evaluate(() => {
  const g = window.game;
  g.hud.backend.data.walletCash += 1_000_000;
  g.world.skyEnvironment.setHour(20);
  const door = g.world.interactiveObjects.find((o) => o.id === 'roadside-eko-grand-hotel');
  g.player.mesh.position.set(door.interactionPoint.x, 0, door.interactionPoint.z);
  g.hud.showInteractionCard(door);
  document.getElementById('card-action-btn')?.click();
});
await inRoom('interior_place_eko-grand-hotel');
await use('place_eko-grand-hotel_reception', 'Two nights');
await play(3);
await wait(600);
await page.screenshot({ path: `${out}/hotel-desk.png` });
await use('place_eko-grand-hotel_lift');
await play(1.6);
await view(-Math.PI / 2, 0.35, 8);
await wait(500);
await page.screenshot({ path: `${out}/hotel-lift.png` });
await inRoom('interior_place_eko-grand-floor');
await view(Math.PI / 2, 0.35, 9);
await play(1);
await wait(600);
await page.screenshot({ path: `${out}/hotel-corridor.png` });
const room = await page.evaluate(() => window.game.modules.HotelStay.get().current().room);
await use(`place_eko-grand-floor_room${room}`);
await play(1.2);
await wait(400);
await page.screenshot({ path: `${out}/hotel-door.png` });
await inRoom('interior_place_eko-grand-suite');
await view(0, 0.55, 11);
await play(1);
await wait(600);
await page.screenshot({ path: `${out}/hotel-room.png` });
await use('place_eko-grand-suite_bed');
await play(5);
await view(0.6, 0.45, 7);
await wait(600);
await page.screenshot({ path: `${out}/hotel-bed.png` });
await page.evaluate(() => window.game.modules.InteractionDirector.get().interrupt(window.game.player.actor));
await play(1);
await use('place_eko-grand-suite_window');
await play(2);
await view(Math.PI, 0.25, 5);
await wait(600);
await page.screenshot({ path: `${out}/hotel-window.png` });
await browser.close();
